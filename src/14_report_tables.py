"""
Step 14 (REPORT): turn the v2 outputs into report-ready tables and figures.

Reads whatever exists of:
  data/v2/collection_log.csv, articles_raw.csv, articles_clean.csv,
  data/v2/annotations_A.csv, results/v2/runs_summary.csv, results/v2/evaluation.csv,
  results/v2/annotation_agreement.txt
and writes to results/v2/report/:
  dataset_overview.csv / .tex     size, days, outlets, collection runs, cleaning losses
  outlet_profile.csv / .tex       per outlet: articles, days, feed success, words (full/capped)
  articles_per_day.png            collection over time, stacked by outlet
  runs_mean_sd.csv / .tex         NPMI, diversity, #topics, outliers: mean +/- sd over seeds
  evaluation_mean_sd.csv / .tex   outlet NMI and event measures: mean +/- sd over seeds
  annotation_summary.csv          labelled articles, events, cross-outlet events
  REPORT_NUMBERS.md               every number above in one readable file

Usage:
    python src/14_report_tables.py
"""

import os
import re
import sys

import numpy as np
import pandas as pd

sys.path.append(os.path.dirname(__file__))
from v2_common import (RAW_PATH, CLEAN_PATH, ANNOTATION_PATH, COLLECTION_LOG_PATH,
                       RESULTS_DIR, ensure_dirs)

OUT = os.path.join(RESULTS_DIR, "report")
md = ["# Report numbers (generated by src/14_report_tables.py)", ""]


def to_tex(df, path, caption, label):
    """Plain booktabs-free tabular that compiles in the ACL template."""
    cols = "l" + "r" * (len(df.columns) - 1)
    esc = lambda s: str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")
    lines = [r"\begin{table}[t]", r"\centering", r"\small", rf"\begin{{tabular}}{{{cols}}}", r"\hline",
             " & ".join(esc(c) for c in df.columns) + r" \\", r"\hline"]
    for _, r in df.iterrows():
        lines.append(" & ".join(esc(v) for v in r.values) + r" \\")
    lines += [r"\hline", r"\end{tabular}", rf"\caption{{{caption}}}", rf"\label{{{label}}}",
              r"\end{table}"]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def add_md(title, df):
    md.extend([f"## {title}", "", df.to_markdown(index=False), ""])


def pm(series, digits=3):
    s = pd.to_numeric(series, errors="coerce").dropna()
    if s.empty:
        return ""
    if len(s) == 1:
        return f"{s.iloc[0]:.{digits}f}"
    return f"{s.mean():.{digits}f} ± {s.std(ddof=1):.{digits}f}"


def dataset_tables():
    if not os.path.isfile(CLEAN_PATH):
        print("No clean articles yet; skipping dataset tables.")
        return
    clean = pd.read_csv(CLEAN_PATH, dtype=str)
    for c in ["words_full", "words_capped"]:
        clean[c] = pd.to_numeric(clean[c], errors="coerce")
    raw = pd.read_csv(RAW_PATH, dtype=str) if os.path.isfile(RAW_PATH) else None
    log = pd.read_csv(COLLECTION_LOG_PATH) if os.path.isfile(COLLECTION_LOG_PATH) else None

    days = sorted(clean["published_date"].unique())
    rows = [("Articles (clean)", len(clean)),
            ("Articles (raw, before cleaning)", len(raw) if raw is not None else "n/a"),
            ("Outlets", clean["outlet"].nunique()),
            ("Days with articles", len(days)),
            ("First / last day", f"{days[0]} / {days[-1]}"),
            ("Mean words per article (full)", f"{clean['words_full'].mean():.1f}"),
            ("Mean words per article (capped)", f"{clean['words_capped'].mean():.1f}")]
    if log is not None:
        rows += [("Collection runs", log["collected_at"].nunique()),
                 ("Feed fetches that failed", int((log["status"] != "ok").sum()))]
    ov = pd.DataFrame(rows, columns=["Property", "Value"])
    ov.to_csv(os.path.join(OUT, "dataset_overview.csv"), index=False)
    to_tex(ov, os.path.join(OUT, "dataset_overview.tex"),
           "Properties of the constructed news dataset.", "tab:dataset")
    add_md("Dataset overview", ov)

    prof = clean.groupby("outlet").agg(
        articles=("article_id", "size"), days=("published_date", "nunique"),
        words_full=("words_full", "mean"), words_capped=("words_capped", "mean")).round(1)
    if log is not None:
        ok = log.assign(ok=log["status"].eq("ok")).groupby("outlet")["ok"].mean()
        prof["feed_success"] = (ok * 100).round(0).astype("Int64").astype(str) + "%"
    prof = prof.reset_index()
    prof.to_csv(os.path.join(OUT, "outlet_profile.csv"), index=False)
    to_tex(prof, os.path.join(OUT, "outlet_profile.tex"),
           "Per-outlet profile. Words are mean words per article before (full) and after "
           "(capped) length control.", "tab:outlets")
    add_md("Per-outlet profile", prof)

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    ct = pd.crosstab(clean["published_date"], clean["outlet"])
    colors = ["#2a78d6", "#eb6834", "#1f9e74", "#8a5cc2", "#c9a227"]
    fig, ax = plt.subplots(figsize=(7.5, 3), dpi=150)
    bottom = np.zeros(len(ct))
    for i, o in enumerate(ct.columns):
        ax.bar(range(len(ct)), ct[o].values, bottom=bottom, color=colors[i % 5], label=o, width=0.8)
        bottom += ct[o].values
    step = max(1, len(ct) // 10)
    ax.set_xticks(range(0, len(ct), step), [d[5:] for d in ct.index[::step]], fontsize=7)
    ax.set_ylabel("Articles", fontsize=8)
    ax.tick_params(labelsize=7)
    for s in ["top", "right"]:
        ax.spines[s].set_visible(False)
    ax.legend(ncol=5, fontsize=7, frameon=False, loc="lower left", bbox_to_anchor=(0, 1.0))
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "articles_per_day.png"))
    plt.close(fig)


def config_of(run):
    return re.sub(r"_seed\d+", "", run)


def runs_tables():
    p = os.path.join(RESULTS_DIR, "runs_summary.csv")
    if not os.path.isfile(p):
        print("No runs_summary.csv yet; skipping model tables.")
        return
    s = pd.read_csv(p)
    offline = s["offline"].astype(str).str.lower().eq("true")
    if ((s["model"] == "BERTopic") & ~offline).any():
        s = s[~offline]  # real runs exist: leave out pipeline smoke tests
    s["config"] = s["run"].map(config_of)
    g = s.groupby("config", sort=False)
    t = pd.DataFrame({
        "config": list(g.groups),
        "seeds": g.size().values,
        "topics": [pm(x["n_topics"], 1) for _, x in g],
        "outliers": [pm(x["outlier_share"], 2) for _, x in g],
        "NPMI": [pm(x["npmi"]) for _, x in g],
        "diversity": [pm(x["diversity"]) for _, x in g],
    })
    t.to_csv(os.path.join(OUT, "runs_mean_sd.csv"), index=False)
    to_tex(t, os.path.join(OUT, "runs_mean_sd.tex"),
           "Topic quality on the constructed dataset (mean ± sd over seeds).", "tab:v2quality")
    add_md("Topic quality per configuration (mean ± sd over seeds)", t)


def eval_tables():
    p = os.path.join(RESULTS_DIR, "evaluation.csv")
    if not os.path.isfile(p):
        print("No evaluation.csv yet; skipping evaluation tables.")
        return
    e = pd.read_csv(p)
    e["config"] = e["run"].map(config_of)
    cols = {"nmi_outlet": "NMI outlet", "nmi_outlet_shuffled": "NMI outlet (shuffled)",
            "nmi_event": "NMI event", "ari_event": "ARI event",
            "together_same_event_cross": "SE/XO", "together_diff_event_same": "DE/SO",
            "together_diff_event_cross": "DE/XO"}
    g = e.groupby("config", sort=False)
    t = pd.DataFrame({"config": list(g.groups), "seeds": g.size().values})
    for c, name in cols.items():
        if c in e:
            t[name] = [pm(x[c]) for _, x in g]
    if "p_outlet" in e:
        t["max p (outlet)"] = [f"{pd.to_numeric(x['p_outlet']).max():.4f}" for _, x in g]
    t = t.loc[:, (t != "").any()]
    t.to_csv(os.path.join(OUT, "evaluation_mean_sd.csv"), index=False)
    to_tex(t, os.path.join(OUT, "evaluation_mean_sd.tex"),
           "Events or outlets? Outlet NMI uses all clustered articles; event measures use the "
           "labelled subset. SE/XO: same-event, cross-outlet pairs kept together; DE/SO and "
           "DE/XO: different-event pairs grouped, same vs different outlet.", "tab:v2eval")
    add_md("Event-vs-outlet evaluation (mean ± sd over seeds)", t)


def annotation_tables():
    if not os.path.isfile(ANNOTATION_PATH):
        return
    a = pd.read_csv(ANNOTATION_PATH, dtype=str).fillna("")
    a["event_id"] = a["event_id"].str.strip().str.upper()
    lab = a[(a["event_id"] != "") & (a["event_id"] != "NONNEWS")]
    if lab.empty:
        md.extend(["## Annotation", "", f"Sheet has {len(a)} rows; none labelled yet.", ""])
        return
    per = lab.groupby("event_id").agg(n=("article_id", "size"), outlets=("outlet", "nunique"))
    t = pd.DataFrame([
        ("Rows in sheet", len(a)), ("Labelled (excl. NONNEWS)", len(lab)),
        ("Days covered", lab["published_date"].nunique()),
        ("Distinct events", len(per)), ("Events with 2+ articles", int((per["n"] > 1).sum())),
        ("Events covered by 2+ outlets", int((per["outlets"] > 1).sum())),
        ("Largest event (articles)", int(per["n"].max()))], columns=["Property", "Value"])
    t.to_csv(os.path.join(OUT, "annotation_summary.csv"), index=False)
    add_md("Annotation", t)
    agr = os.path.join(RESULTS_DIR, "annotation_agreement.txt")
    if os.path.isfile(agr):
        md.extend(["## Inter-annotator agreement", "", "```", open(agr).read().strip(), "```", ""])


def main():
    ensure_dirs()
    os.makedirs(OUT, exist_ok=True)
    dataset_tables()
    annotation_tables()
    runs_tables()
    eval_tables()
    lj = os.path.join(RESULTS_DIR, "llm_judge", "llm_judge_summary.csv")
    if os.path.isfile(lj):
        add_md("LLM-as-judge (src/15_llm_judge.py)", pd.read_csv(lj))
    lx = os.path.join(RESULTS_DIR, "llm_judge", "llm_judge_summary_extra.csv")
    if os.path.isfile(lx):
        add_md("LLM-as-judge on replication / Amazon topics (Q1 only)", pd.read_csv(lx))
    with open(os.path.join(OUT, "REPORT_NUMBERS.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print("\n".join(md))
    print(f"\nSaved tables, figures and REPORT_NUMBERS.md to {OUT}/")


if __name__ == "__main__":
    main()
